package com.exam.model;

public class PlayerViewModel {private int id;
    private int playerId;
    private String playerName;
    private String playerAge;
    private int indexId;
    private String indexName;
    private float value;

    public int getId() { return id; }
    public void setId(int id) { this.id = id; }
    public int getPlayerId() { return playerId; }
    public void setPlayerId(int playerId) { this.playerId = playerId; }
    public String getPlayerName() { return playerName; }
    public void setPlayerName(String playerName) { this.playerName = playerName; }
    public String getPlayerAge() { return playerAge; }
    public void setPlayerAge(String playerAge) { this.playerAge = playerAge; }
    public int getIndexId() { return indexId; }
    public void setIndexId(int indexId) { this.indexId = indexId; }
    public String getIndexName() { return indexName; }
    public void setIndexName(String indexName) { this.indexName = indexName; }
    public float getValue() { return value; }
    public void setValue(float value) { this.value = value; }
}
